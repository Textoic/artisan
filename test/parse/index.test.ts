type Expected = {
  id: number;
  form: string;
  xpos: string;
  head: number;
  acceptedXpos?: string[];
  acceptedHeads?: number[];
};

const tagProblems = (
  token: Expected,
  parsed: ParsedToken,
  index: number,
  name: string,
) => {
  if (parsed.xpos === token.xpos || token.acceptedXpos?.includes(parsed.xpos)) {
    return [];
  }

  const allowed = [token.xpos, ...(token.acceptedXpos ?? [])].join(" or ");
  return [
    `${name}: "${token.form}" (${index}) was tagged ${parsed.xpos}, expected ${allowed}`,
  ];
};

const headProblems = (
  token: Expected,
  parsed: ParsedToken,
  index: number,
  name: string,
) => {
  if (
    parsed.head === token.head ||
    token.acceptedHeads?.includes(parsed.head)
  ) {
    return [];
  }

  const allowed = [token.head, ...(token.acceptedHeads ?? [])].join(" or ");
  return [
    `${name}: "${token.form}" (${index}) got head ${parsed.head}, expected ${allowed}`,
  ];
};

const recordPrediction = (token: Expected, parsed: ParsedToken) => {
  if (!parsed.isDisambiguated) {
    return;
  }

  totalPredictions += 1;
  if (parsed.xpos === token.xpos) {
    correctPredictions += 1;
  }
};

const check = (text: string, expected: Expected[], name: string) => {
  const actual = parse(tokenize(text, { dictionary }));
  if (actual.length !== expected.length) {
    return [
      `${name}: tokenized "${text}" into ${actual.length} tokens, expected ${expected.length}`,
    ];
  }

  return expected.flatMap((token, index) => {
    const parsed = actual[index];
    recordPrediction(token, parsed);
    return [
      ...tagProblems(token, parsed, index, name),
      ...headProblems(token, parsed, index, name),
    ];
  });
};

describe("parse", () => {
  tests
    .filter(([, , name]) => !KNOWN_GAPS.has(name))
    .forEach(([text, expected, name]) => {
      it(name, () => {
        const problems = check(text, expected, name);
        assert.equal(problems.length, 0, problems.join("; "));
      });
    });
});

describe("parse: known gaps", () => {
  const names = tests.map(([, , name]) => name);
  KNOWN_GAPS.forEach((name) => {
    if (!names.includes(name)) {
      it(`stale known gap: ${name}`, () => {
        assert.fail(
          `"${name}" is listed as a known gap but no such test exists; remove it from KNOWN_GAPS`,
        );
      });
    }
  });

  tests
    .filter(([, , name]) => KNOWN_GAPS.has(name))
    .forEach(([text, expected, name]) => {
      it(name, (t) => {
        const problems = check(text, expected, name);
        t.diagnostic(
          problems.length === 0
            ? `now passes with the rules alone; remove it from KNOWN_GAPS`
            : problems.join("; "),
        );
      });
    });
});

describe("parse: accuracy", () => {
  it("ambiguous words are tagged above the threshold", (t) => {
    const accuracy = correctPredictions / totalPredictions;
    t.diagnostic(
      `${correctPredictions} of ${totalPredictions} ambiguous words tagged correctly with the rules alone (${(100 * accuracy).toFixed(2)}%)`,
    );
    assert.ok(
      accuracy > DISAMBIGUATION_ACCURACY_THRESHOLD,
      `tagged ${correctPredictions} of ${totalPredictions} ambiguous words correctly (${(100 * accuracy).toFixed(2)}%), below the ${(100 * DISAMBIGUATION_ACCURACY_THRESHOLD).toFixed(0)}% floor`,
    );
  });
});
